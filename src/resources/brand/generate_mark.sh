#!/usr/bin/env bash
# Generates the app mark's and logo's derived files from reckless_mark.svg and
# reckless_wordmark_{black,white}.svg:
#   src/resources/icon/reckless_mark.h   the SVG embedded as a C++ raw string
#   src/resources/icon/reckless_wordmark_{black,white}.h, the same for the logo
#   src/resources/brand/png/reckless_wordmark_{black,white}_<WxH>.png, 300, 600 and 1200 px wide
#   src/resources/brand/png/reckless_mark_<size>.png at 16, 24, 32, 48, 64, 128, 256, 512
#   src/resources/brand/reckless.ico and reckless.icns, the Windows and macOS app icons
#   (pack_icons.py, from those PNGs and a 1024 px one for macOS)
# The PNGs come from Qt's SVG renderer (render_mark.cpp), the one the app draws with.
# CMake checks at configure time that the header holds the SVG unchanged.
#
# Usage: ./generate_mark.sh   (needs a C++ compiler and Qt 6 Gui/Svg through pkg-config)

set -euo pipefail

DIR="$(cd "$(dirname "$0")" && pwd)"
SVG="$DIR/reckless_mark.svg"
PNG_DIR="$DIR/png"
SIZES=(16 24 32 48 64 128 256 512)
# The full logo (ws-plaude/silent#120), dark letters for light themes and white ones for
# dark themes, at 1x, 2x and 4x of its 300 px width on the welcome screen.
WORDMARKS=(black white)
WORDMARK_SIZES=(300x76 600x152 1200x303)

# embed <svg> <header> <constant> <comment>: the SVG as a C++ raw string.
embed() {
    if grep -q ')svg"' "$1"; then
        echo "Error: $1 contains the raw string delimiter )svg\"" >&2
        exit 1
    fi
    {
        printf '#pragma once\n\n'
        printf '// Generated by src/resources/brand/generate_mark.sh from %s; do not edit.\n' "$(basename "$1")"
        printf '// %s\n\n' "$4"
        printf 'namespace embedded_icon {\n\n'
        printf 'constexpr char %s[] = R"svg(' "$3"
        cat "$1"
        printf ')svg";\n\n'
        printf '} // namespace embedded_icon\n'
    } > "$2"
}

embed "$SVG" "$DIR/../icon/reckless_mark.h" RECKLESS_MARK \
    "The reckless app mark, drawn in its own colours."
for tone in "${WORDMARKS[@]}"; do
    upper=$(printf '%s' "$tone" | tr '[:lower:]' '[:upper:]')
    embed "$DIR/reckless_wordmark_$tone.svg" "$DIR/../icon/reckless_wordmark_$tone.h" \
        "RECKLESS_WORDMARK_$upper" "The full reckless logo, its letters $tone."
done
# HEADERS_ONLY=1 stops here: the PNGs and icons need a C++ compiler.
if [ "${HEADERS_ONLY:-}" = 1 ]; then
    echo "Wrote the mark and wordmark headers"
    exit 0
fi

TOOL_DIR=$(mktemp -d)
trap 'rm -rf "$TOOL_DIR"' EXIT
# shellcheck disable=SC2046
c++ -std=c++17 -fPIC "$DIR/render_mark.cpp" -o "$TOOL_DIR/render_mark" \
    $(pkg-config --cflags --libs Qt6Svg Qt6Gui)
mkdir -p "$PNG_DIR"
"$TOOL_DIR/render_mark" "$SVG" "$PNG_DIR/reckless_mark_" "${SIZES[@]}"
# The 1024 px render is only for the macOS 512@2x entry.
cp "$PNG_DIR"/reckless_mark_*.png "$TOOL_DIR/"
"$TOOL_DIR/render_mark" "$SVG" "$TOOL_DIR/reckless_mark_" 1024
python3 "$DIR/pack_icons.py" "$TOOL_DIR" reckless_mark_ "$DIR"
for tone in "${WORDMARKS[@]}"; do
    "$TOOL_DIR/render_mark" "$DIR/reckless_wordmark_$tone.svg" \
        "$PNG_DIR/reckless_wordmark_${tone}_" "${WORDMARK_SIZES[@]}"
done

echo "Wrote the mark and wordmark headers, the PNGs in $PNG_DIR, reckless.ico and reckless.icns"
